import { Schema, model, type InferSchemaType, type Types } from 'mongoose';
import {
  CURRENCIES,
  EVENT_CATEGORIES,
  EVENT_STATUSES,
  LIMITS,
  NUMBERING,
  PALETTE,
  ROW_LABEL,
  SECTION_CODE,
} from '@seatbook/shared';

const maxLen = (n: number) => ({
  validator: (a: unknown[]) => a.length <= n,
  message: `At most ${n} items`,
});

const rowSchema = new Schema(
  {
    label: { type: String, required: true, match: ROW_LABEL },
    seats: { type: Number, required: true, min: 1, max: LIMITS.seatsPerRow },
    offset: { type: Number, default: 0, min: 0, max: LIMITS.maxRowOffset },
    tierId: { type: Schema.Types.ObjectId, required: true }, // → tiers._id
    gapsAfter: { type: [Number], default: [] }, // aisle after these seat numbers
    blocked: { type: [Number], default: [] }, // not for sale
  },
  { _id: false },
);

const sectionSchema = new Schema(
  {
    // _id is generated by the CLIENT (24-hex) so rows can reference tiers before the first save.
    name: { type: String, required: true, trim: true, minlength: 1, maxlength: 40 },
    code: { type: String, required: true, match: SECTION_CODE },
    x: { type: Number, required: true, min: 0, max: LIMITS.gridSize },
    y: { type: Number, required: true, min: 0, max: LIMITS.gridSize },
    numbering: { type: String, enum: NUMBERING, default: 'ltr' },
    rows: { type: [rowSchema], default: [], validate: maxLen(LIMITS.rowsPerSection) },
  },
  { _id: true },
);

const tierSchema = new Schema(
  {
    name: { type: String, required: true, trim: true, minlength: 1, maxlength: 30 },
    price: { type: Number, required: true, min: 0, max: LIMITS.maxPrice }, // minor units
    color: { type: String, enum: PALETTE, required: true },
  },
  { _id: true },
);

const countersSchema = new Schema(
  {
    seatsTotal: { type: Number, default: 0 },
    seatsSellable: { type: Number, default: 0 },
    seatsSold: { type: Number, default: 0 },
    ticketsCheckedIn: { type: Number, default: 0 },
    revenue: { type: Number, default: 0 }, // minor units, confirmed bookings
  },
  { _id: false },
);

const eventSchema = new Schema(
  {
    organizerId: { type: Schema.Types.ObjectId, ref: 'User', required: true, immutable: true },
    title: { type: String, required: true, trim: true, minlength: 3, maxlength: 120 },
    slug: { type: String, required: true, lowercase: true, trim: true, maxlength: 140 },
    summary: { type: String, trim: true, maxlength: 200, default: '' },
    description: { type: String, maxlength: 5000, default: '' }, // Markdown, rendered safely
    category: { type: String, enum: EVENT_CATEGORIES, default: 'other' },
    venue: {
      name: { type: String, required: true, trim: true, minlength: 2, maxlength: 100 },
      address: { type: String, trim: true, maxlength: 200, default: '' },
      city: { type: String, required: true, trim: true, minlength: 2, maxlength: 60 },
    },
    timezone: { type: String, required: true },
    startsAt: { type: Date, required: true },
    endsAt: { type: Date, required: true },
    salesStartAt: { type: Date, default: null }, // null until publish → publish time
    salesEndAt: { type: Date, default: null }, // null → startsAt
    currency: { type: String, enum: CURRENCIES, default: 'USD' },
    maxSeatsPerOrder: {
      type: Number,
      min: 1,
      max: LIMITS.maxSeatsPerOrder,
      default: LIMITS.defaultSeatsPerOrder,
    },
    coverColor: { type: String, enum: PALETTE, default: 'indigo' },
    refundsAllowed: { type: Boolean, default: false },

    seatMap: {
      stageLabel: { type: String, trim: true, maxlength: 30, default: 'STAGE' },
      sections: { type: [sectionSchema], default: [], validate: maxLen(LIMITS.sectionsPerEvent) },
    },
    tiers: { type: [tierSchema], default: [], validate: maxLen(LIMITS.tiersPerEvent) },

    status: { type: String, enum: EVENT_STATUSES, default: 'draft' },
    revision: { type: Number, default: 1 }, // CAS for draft edits (data-model.md D4)
    publishedAt: { type: Date, default: null },
    cancelledAt: { type: Date, default: null },
    cancelReason: { type: String, maxlength: 500, default: null },
    counters: { type: countersSchema, default: () => ({}) },
  },
  { collection: 'events', timestamps: true, versionKey: false },
);

eventSchema.index({ slug: 1 }, { unique: true, name: 'uniq_event_slug' });
eventSchema.index({ organizerId: 1, startsAt: -1 }); // AP21 my events
eventSchema.index({ status: 1, startsAt: 1 }); // AP2 public listing
// Should: text search (FR-EVT-13)
// eventSchema.index({ title: 'text', 'venue.name': 'text', 'venue.city': 'text' });

export type EventDoc = InferSchemaType<typeof eventSchema>;
/** Mongoose infers these as optional, but the schema always fills them in. */
export type EventLean = Omit<EventDoc, 'venue' | 'salesStartAt' | 'salesEndAt'> & {
  _id: Types.ObjectId;
  venue: { name: string; address: string; city: string };
  salesStartAt: Date | null;
  salesEndAt: Date | null;
};
export const Event = model('Event', eventSchema);
